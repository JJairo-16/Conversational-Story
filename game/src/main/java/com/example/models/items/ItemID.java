package com.example.models.items;

/**
 * Stable identifiers for all game items.
 */
public enum ItemID {
    /** Donut used as a temporary distraction for Malien. */
    DONUT,

    /** Astronaut suit required to survive outside the ship. */
    ASTRONAUT_SUIT,

    /** Tool required to repair the propulsors. */
    REPAIR_TOOL,

    /** Crew card used as a possible door-opening aid. */
    CREW_CARD,

    /** Snorkel required to retrieve an item from the flooded bathroom. */
    SNORKEL,

    /** Flashlight required to search dark rooms. */
    FLASHLIGHT,

    /** Small key used to open the astronaut suit locker. */
    SMALL_KEY;
}
